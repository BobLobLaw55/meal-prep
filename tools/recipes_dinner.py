"""Dinner batches. Each batch = tonight's dinner + tomorrow's lunch for both of you.
Default split: A gets ~32.5% of the batch per meal, B ~17.5% (x2 meals each = 100%).
`prep` = what to do ahead on the Sun/Wed prep session.
"""

D = []

def add(**r):
    r.setdefault("meal", "dinner")
    r.setdefault("heat", "mild")
    r.setdefault("nA", 2)
    r.setdefault("nB", 2)
    r.setdefault("split", (0.325, 0.175))
    r.setdefault("portion", {"A": "About ⅓ of the batch", "B": "About ⅙ of the batch"})
    D.append(r)

